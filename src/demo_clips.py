"""
Clips for the demo (Phase 4), generated from the hand-picked prompts of
configs/demo_prompts.csv.

The character of a clip comes from its prompt (a few seconds of a calm or
of a battle passage) and its intensity from the controls (E2: tension sets
the level, combat score adds a percussive character at high tension).
Clips longer than one 10-second window are generated by sliding windows
(generation.generate_long_codes).

  pilot  A few trial clips to choose the settings by ear: 3 chill and
         3 fight passages, one clip each.
  sweep  The pilot passages again under several settings, each differing
         from the pilot ("base") in one choice only (sampling temperature,
         controls, context, prompt length), with the same seeds, so that
         two folders can be compared clip by clip. It also writes, once
         per passage, the real continuation decoded from its first 8
         codebooks (reference/*_codec8.wav): the best a generated clip
         could sound through the same codec.
  bank   One clip (or --takes clips) for every passage of
         configs/demo_prompts.csv with the chosen settings, to pick the
         clips of the demo by ear. By default 5 s of prompt and 5 s of
         generated audio: prompt and clip fit in one 10-s window, so there
         is no sliding and no window change.

Every clip is written twice: `*_with_prompt.wav` (real prompt + generated
continuation, to judge how the continuation follows the prompt; never
published) and `*_generated.wav` (generated audio only, the version that
can go into the demo). The reference files are real music: never published.

Run from the repository root (CPU is enough, about 2x real time with the
key/value cache, i.e. about 40 s per 15-second clip):
    python src/demo_clips.py pilot
    python src/demo_clips.py pilot --prompt-seconds 3 --generated-seconds 15
    python src/demo_clips.py sweep
    python src/demo_clips.py sweep --settings base fine_t07
    python src/demo_clips.py bank --settings fine_t07
    python src/demo_clips.py bank --settings fine_t07 --takes 2
"""

import argparse
import csv
import sys
import time
from pathlib import Path

import numpy as np
import torch

from frame_codec import NUM_CODEBOOKS
from generation import (
    DEFAULT_TEMPERATURE,
    FRAME_RATE,
    SAMPLE_RATE,
    decode_codes,
    generate_long_codes,
    load_codec,
    save_wav,
)
from paths import get_path
from prompt_candidates import CONFIG_PATH, load_tensor, parse_time, write_table
from training_utils import load_checkpoint_model


PROJECT_ROOT = Path(__file__).resolve().parents[1]
PILOT_DIR = PROJECT_ROOT / "outputs" / "demo_pilot"
SWEEP_DIR = PROJECT_ROOT / "outputs" / "demo_sweep"
BANK_DIR = PROJECT_ROOT / "outputs" / "demo_bank"

# Requested controls after the prompt. Fight uses the high levels of E2
# (90th percentiles of the training conditions); chill keeps a low combat
# score and a moderate tension, since tension 0.14 (E2 "low") is very quiet.
TARGETS = {
    "chill": {"tension": 0.30, "combat_score": 0.21},
    "fight": {"tension": 0.77, "combat_score": 0.85},
}
RAMP_SECONDS = 1.0      # from the prompt's own level to the target (avoids a jump)
FADE_SECONDS = 0.02
CONTEXT_SECONDS = 5.0   # context of every sliding window after the first

# (title, start) of the pilot passages in configs/demo_prompts.csv.
PILOT_PASSAGES = (
    ("Secunda", "0:14"),
    ("Kaer Morhen", "0:14"),
    ("From Past to Present", "0:29"),
    ("One They Fear", "0:00"),
    ("Hunt or Be Hunted", "0:00"),
    ("Dragonborn", "0:35"),
)

# Each setting changes one choice of the pilot ("base"):
#   fine_t07      temperature 0.7 for Q1-Q7 only: the residual codebooks add
#                 detail to Q0, and sampling them less randomly should add
#                 less noise, while Q0 keeps the variety of temperature 1.0
#   all_t08       temperature 0.8 for every codebook (the usual knob: less
#                 noise, but also less variety)
#   prompt_level  the controls stay at the prompt's own level instead of
#                 moving to the chill/fight target (does the push to a far
#                 level cause the distortion?)
#   context_8s    8 s of context in the sliding windows instead of 5 s
#                 (smoother change at the window boundary?)
#   prompt_5s     5 s of prompt instead of 3 s
SWEEP_SETTINGS = {
    "base": {},
    "fine_t07": {"temperature": (1.0,) + (0.7,) * (NUM_CODEBOOKS - 1)},
    "all_t08": {"temperature": 0.8},
    "prompt_level": {"hold_prompt_level": True},
    "context_8s": {"context_seconds": 8.0},
    "prompt_5s": {"prompt_seconds": 5.0},
}

# (prompt seconds, generated seconds) when not given on the command line.
DEFAULT_SECONDS = {"pilot": (3.0, 15.0), "sweep": (3.0, 15.0), "bank": (5.0, 5.0)}


def control_track(prompt_values, target, total_frames, ramp_frames):
    """
    Prompt's own values, then a linear ramp from their last 0.5 s mean to
    `target`. With target=None the track stays at that mean.
    """
    prompt_values = torch.as_tensor(prompt_values, dtype=torch.float32)
    prompt_frames = prompt_values.shape[0]
    start_value = float(prompt_values[-FRAME_RATE // 2:].mean())
    if target is None:
        target = start_value
    track = torch.full((total_frames,), float(target))
    track[:prompt_frames] = prompt_values
    ramp_end = min(prompt_frames + ramp_frames, total_frames)
    track[prompt_frames:ramp_end] = torch.linspace(start_value, float(target), ramp_end - prompt_frames)
    return track.clamp(0.0, 1.0)


def slug(text):
    return "".join(c.lower() if c.isalnum() else "_" for c in text).strip("_")


def clip_name(passage):
    return f"{passage['label']}_{slug(passage['title'])}_{passage['start'].replace(':', 'm')}"


def load_all_passages():
    with open(CONFIG_PATH, newline="", encoding="utf-8") as file:
        return list(csv.DictReader(file))


def load_passages(selection):
    passages = load_all_passages()
    chosen = []
    for title, start in selection:
        matches = [p for p in passages if p["title"].strip(". ").endswith(title) and p["start"] == start]
        if len(matches) != 1:
            raise ValueError(f"{title} {start}: expected one passage in {CONFIG_PATH}, found {len(matches)}.")
        chosen.append(matches[0])
    return chosen


def generate_clip(
    model,
    codec,
    passage,
    prompt_seconds,
    generated_seconds,
    seed,
    device,
    temperature=DEFAULT_TEMPERATURE,
    context_seconds=CONTEXT_SECONDS,
    hold_prompt_level=False,
):
    """Returns (waveform, prompt_frames, final tension, final combat score)."""
    data = load_tensor(get_path(passage["source"]) / passage["tensor_file"])
    prompt_frames = int(round(prompt_seconds * FRAME_RATE))
    total_frames = prompt_frames + int(round(generated_seconds * FRAME_RATE))
    start = int(round(parse_time(passage["start"]) * FRAME_RATE))

    prompt = data["tokens"][:NUM_CODEBOOKS, start:start + prompt_frames].long().unsqueeze(0).to(device)
    target = {"tension": None, "combat_score": None} if hold_prompt_level else TARGETS[passage["label"]]
    ramp = int(RAMP_SECONDS * FRAME_RATE)
    tension = control_track(data["tension"][start:start + prompt_frames], target["tension"], total_frames, ramp)
    combat = control_track(data["combat_score"][start:start + prompt_frames], target["combat_score"], total_frames, ramp)

    codes = generate_long_codes(
        model, prompt, tension[None].to(device), combat[None].to(device),
        context_frames=int(round(context_seconds * FRAME_RATE)), seed=seed, temperature=temperature,
    )
    waveform = decode_codes(codec, codes)[0].numpy()
    return waveform, prompt_frames, float(tension[-1]), float(combat[-1])


def rms_dbfs(audio):
    return round(float(20 * np.log10(np.sqrt(np.mean(np.square(audio))) + 1e-12)), 1)


def write_clip(out_dir, name, waveform, prompt_frames):
    """Writes *_with_prompt.wav and *_generated.wav; returns their levels and clipping."""
    save_wav(out_dir / f"{name}_with_prompt.wav", waveform)

    prompt_samples = prompt_frames * SAMPLE_RATE // FRAME_RATE
    generated = waveform[prompt_samples:].copy()
    fade = int(FADE_SECONDS * SAMPLE_RATE)
    generated[:fade] *= np.linspace(0.0, 1.0, fade)
    clipped = save_wav(out_dir / f"{name}_generated.wav", generated)

    return {"prompt_rms_dbfs": rms_dbfs(waveform[:prompt_samples]), "rms_dbfs": rms_dbfs(generated),
            "clipped_fraction": clipped}


def load_model_and_codec(args):
    device = torch.device(args.device)
    checkpoint = Path(args.checkpoint) if args.checkpoint else get_path("ckpt_ost_ft")
    if not checkpoint.exists():
        raise FileNotFoundError(
            f"{checkpoint} not found. Download the OST-FT checkpoint from Kaggle "
            "(model secunda-finetuned-on-ost-v2) into checkpoints/, or pass --checkpoint."
        )
    model, _ = load_checkpoint_model(checkpoint, device)
    return model, load_codec(device), device


def command_pilot(args):
    model, codec, device = load_model_and_codec(args)
    PILOT_DIR.mkdir(parents=True, exist_ok=True)
    rows = []

    for index, passage in enumerate(load_passages(PILOT_PASSAGES)):
        started = time.time()
        waveform, prompt_frames, _, _ = generate_clip(
            model, codec, passage, args.prompt_seconds, args.generated_seconds, seed=args.seed + index, device=device
        )
        name = clip_name(passage)
        levels = write_clip(PILOT_DIR, name, waveform, prompt_frames)

        seconds = time.time() - started
        rows.append({"clip": name, "label": passage["label"], "title": passage["title"],
                     "prompt_start": passage["start"], "prompt_seconds": args.prompt_seconds,
                     "generated_seconds": args.generated_seconds, "seed": args.seed + index,
                     **levels, "generation_seconds": round(seconds, 1)})
        print(f"{name:45s} {seconds:5.1f} s  ({rows[-1]['rms_dbfs']} dBFS)")

    write_table(rows, PILOT_DIR / "clips.csv")
    print(f"{len(rows)} clips -> {PILOT_DIR}")


def write_reference(codec, passage, total_seconds, out_dir):
    """Real codes Q0-Q7 from the prompt start, decoded: the codec ceiling of a generated clip."""
    data = load_tensor(get_path(passage["source"]) / passage["tensor_file"])
    start = int(round(parse_time(passage["start"]) * FRAME_RATE))
    end = min(start + int(round(total_seconds * FRAME_RATE)), data["tokens"].shape[-1])
    codes = data["tokens"][:NUM_CODEBOOKS, start:end].long().unsqueeze(0)
    device = next(codec.parameters()).device
    save_wav(out_dir / f"{clip_name(passage)}_codec8.wav", decode_codes(codec, codes.to(device))[0].numpy())


def setting_options(setting, prompt_seconds):
    """generate_clip options of a setting of SWEEP_SETTINGS."""
    return {"prompt_seconds": prompt_seconds, "context_seconds": CONTEXT_SECONDS,
            "temperature": DEFAULT_TEMPERATURE, "hold_prompt_level": False, **SWEEP_SETTINGS[setting]}


def run_clip(model, codec, passage, out_dir, name, setting, options, generated_seconds, seed, device):
    """Generates and writes one clip; returns its row for the clips table."""
    started = time.time()
    waveform, prompt_frames, final_tension, final_combat = generate_clip(
        model, codec, passage, generated_seconds=generated_seconds, seed=seed, device=device, **options,
    )
    levels = write_clip(out_dir, name, waveform, prompt_frames)

    seconds = time.time() - started
    temperature = options["temperature"]
    print(f"{setting:13s} {name:43s} {seconds:5.1f} s  (prompt {levels['prompt_rms_dbfs']} dBFS, "
          f"generated {levels['rms_dbfs']} dBFS)")
    return {"setting": setting, "clip": name, "label": passage["label"], "title": passage["title"],
            "prompt_start": passage["start"], "prompt_seconds": options["prompt_seconds"],
            "generated_seconds": generated_seconds, "context_seconds": options["context_seconds"],
            "temperature": temperature if isinstance(temperature, (int, float))
            else " ".join(f"{t:g}" for t in temperature),
            "target_tension": round(final_tension, 3), "target_combat": round(final_combat, 3),
            "seed": seed, **levels, "generation_seconds": round(seconds, 1)}


def command_sweep(args):
    model, codec, device = load_model_and_codec(args)
    passages = load_passages(PILOT_PASSAGES)
    print(f"{len(args.settings)} settings x {len(passages)} passages = {len(args.settings) * len(passages)} clips "
          f"(about 40 s each on a CPU)")

    reference_dir = SWEEP_DIR / "reference"
    reference_dir.mkdir(parents=True, exist_ok=True)
    for passage in passages:
        write_reference(codec, passage, args.prompt_seconds + args.generated_seconds, reference_dir)

    rows = []
    for setting in args.settings:
        options = setting_options(setting, args.prompt_seconds)
        out_dir = SWEEP_DIR / setting
        out_dir.mkdir(parents=True, exist_ok=True)
        for index, passage in enumerate(passages):
            rows.append(run_clip(model, codec, passage, out_dir, clip_name(passage), setting, options,
                                 args.generated_seconds, seed=args.seed + index, device=device))

        # Written after every setting, so an interrupted sweep keeps its table.
        write_table(rows, SWEEP_DIR / "clips.csv")

    print(f"{len(rows)} clips -> {SWEEP_DIR}")


def command_bank(args):
    model, codec, device = load_model_and_codec(args)
    passages = load_all_passages()
    clips = len(args.settings) * len(passages) * args.takes
    print(f"{len(args.settings)} settings x {len(passages)} passages x {args.takes} takes = {clips} clips "
          f"(about {2.7 * args.generated_seconds + 2:.0f} s each on a CPU)")

    for setting in args.settings:
        options = setting_options(setting, args.prompt_seconds)
        out_dir = BANK_DIR / setting
        out_dir.mkdir(parents=True, exist_ok=True)
        rows = []
        for take in range(args.takes):
            for index, passage in enumerate(passages):
                name = f"{clip_name(passage)}_t{take + 1}"
                rows.append(run_clip(model, codec, passage, out_dir, name, setting, options,
                                     args.generated_seconds, seed=args.seed + 100 * take + index, device=device))
            write_table(rows, out_dir / "clips.csv")
        print(f"{len(rows)} clips -> {out_dir}")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=tuple(DEFAULT_SECONDS))
    parser.add_argument("--checkpoint", default=None, help="default: OST-FT (paths.py, ckpt_ost_ft)")
    parser.add_argument("--prompt-seconds", type=float, default=None,
                        help="default: 3 (pilot, sweep), 5 (bank)")
    parser.add_argument("--generated-seconds", type=float, default=None,
                        help="default: 15 (pilot, sweep), 5 (bank)")
    parser.add_argument("--settings", nargs="+", choices=tuple(SWEEP_SETTINGS), default=None,
                        help="sweep and bank: settings to run (default: all for sweep, base for bank)")
    parser.add_argument("--takes", type=int, default=1, help="bank only: clips per passage (different seeds)")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    args = parser.parse_args(argv)

    prompt_seconds, generated_seconds = DEFAULT_SECONDS[args.command]
    if args.prompt_seconds is None:
        args.prompt_seconds = prompt_seconds
    if args.generated_seconds is None:
        args.generated_seconds = generated_seconds
    if args.settings is None:
        args.settings = list(SWEEP_SETTINGS) if args.command == "sweep" else ["base"]

    commands = {"pilot": command_pilot, "sweep": command_sweep, "bank": command_bank}
    commands[args.command](args)


if __name__ == "__main__":
    sys.exit(main())
