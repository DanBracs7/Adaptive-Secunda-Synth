"""
Playable demo page (docs/index.html, for GitHub Pages).

A small top-down scene: the player walks with the arrow keys (or WASD, or
the on-screen pad). Entering the enemy camp switches the requested controls
from exploration to combat (the chill and fight targets of
src/demo_clips.py), and the music crossfades between two pools of clips
generated in advance with those controls. The pools are the clips kept in
outputs/demo_bank/demo_selection.csv (exported by the page of
src/demo_review.py). Only the generated part of a clip is embedded, never
its game-music prompt.

A second section plays clips of experiment E2 (notebook 05) generated by
Slakh-FT from Slakh2100 test prompts. Slakh2100 is CC BY 4.0, so these
clips keep their 1-s real prompt: the same prompt with exploration-level
and combat-level controls, and the tension step at 5 s of Figure 1.

All audio is embedded as MP3 in one HTML file, so the page works on GitHub
Pages and from disk.

Run from the repository root (needs the WAV files of the bank and of
notebook 05):
    python src/demo_page.py
    python src/demo_page.py --experiment-prompts 3 4 7
"""

