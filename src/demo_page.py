def load_selection(selection_csv=SELECTION_CSV):
    """Rows of demo_selection.csv marked keep = 1."""
    with open(selection_csv, newline="", encoding="utf-8") as file:
        return [row for row in csv.DictReader(file) if row["keep"].strip() == "1"]


def find_bank_row(bank_dir, setting, clip):
    """Row of a clip in its folder's loops.csv or clips.csv."""
    folder = Path(bank_dir) / setting
    for table in (folder / "loops.csv", folder / "clips.csv"):
        if table.exists():
            with open(table, newline="", encoding="utf-8") as file:
                for row in csv.DictReader(file):
                    if row["clip"] == clip:
                        return row
    raise KeyError(f"{setting}/{clip}: not in {folder}/loops.csv or clips.csv")


def mp3_base64(wav_path):
    audio, rate = soundfile.read(str(wav_path), dtype="float32")
    if rate != SAMPLE_RATE:
        raise ValueError(f"{wav_path}: {rate} Hz, expected {SAMPLE_RATE}")
    if audio.ndim > 1:
        audio = audio.mean(axis=1)
    return base64.b64encode(encode_mp3(audio, rate)).decode("ascii")


def collect_pools(selection, bank_dir=BANK_DIR):
    """
    {label: [clip]} for the kept clips, each clip {title, prompt_start,
    audio}: audio is the key of the embedded MP3 of the generated part.
    Returns (pools, audio).
    """
    pools, audio = {label: [] for label in TARGETS}, {}
    for row in selection:
        bank_row = find_bank_row(bank_dir, row["setting"], row["clip"])
        generated, _ = clip_files(row["setting"], bank_row)       # the prompt file is never read
        key = f"bank/{generated}"
        audio[key] = mp3_base64(Path(bank_dir) / generated)
        pools.setdefault(row["label"], []).append(
            {"title": row["title"], "prompt_start": row["prompt_start"], "audio": key})
    for label, clips in pools.items():
        if not clips:
            raise ValueError(f"No kept {label} clip in the selection: keep at least one per label.")
    return pools, audio


def collect_experiment(prompts=EXPERIMENT_PROMPTS, audio_dir=AUDIO_DIR, seed=EXPERIMENT_SEED):
    """[{prompt, clips: [{label, audio}]}] and the embedded MP3s of the E2 clips."""
    examples, audio = [], {}
    for prompt in prompts:
        clips = []
        for condition, label in EXPERIMENT_CONDITIONS:
            path = clip_path(audio_dir, "Slakh-FT", prompt, seed, condition)
            key = f"e2/{path.name}"
            audio[key] = mp3_base64(path)
            clips.append({"label": label, "audio": key})
        examples.append({"prompt": prompt, "clips": clips})
    return examples, audio


