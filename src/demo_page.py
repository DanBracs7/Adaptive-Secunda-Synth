EXPERIMENT_INTRO = (
    "<h2>What the controls alone do, same prompt but different requests</h2>"
    "<p>Each row starts from the same second of a Slakh2100 (CC BY 4.0) test song  and continues it three times with the same random numbers; only the requested controls change: low, high, or a step from low to high at 5 s (the experiment of Figure 1 in the report). The three songs were picked by a rule, not by ear: their measured change is the closest to the median of the 12 test prompts.</p>"
)


def build_page(pools, examples, audio):
    """Return the demo page as a string (no experiment section when `examples` is empty)."""
    cards = []
    for index, example in enumerate(examples, start=1):
        players = "".join(
            f'<div class="muted">{html.escape(clip["label"])}</div>'
            f'<audio controls preload="none" data-audio="{html.escape(clip["audio"])}"></audio>'
            for clip in example["clips"])
        cards.append(f'<div class="card"><b>Slakh2100 prompt {index}</b>{players}</div>')
    section = f'{EXPERIMENT_INTRO}<div class="examples">{"".join(cards)}</div>' if cards else ""
    return (PAGE_TEMPLATE
            .replace("__EXPERIMENT_SECTION__", section)
            .replace("__REPO__", html.escape(REPOSITORY_URL))
            .replace("__POOLS__", json.dumps(pools, ensure_ascii=False))
            .replace("__TARGETS__", json.dumps(TARGETS))
            .replace("__AUDIO__", json.dumps(audio)))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--selection", type=Path, default=SELECTION_CSV)
    parser.add_argument("--bank-dir", type=Path, default=BANK_DIR)
    parser.add_argument("--audio-dir", type=Path, default=AUDIO_DIR, help="WAV files of notebook 05")
    parser.add_argument("--experiment-prompts", type=int, nargs="*", default=list(EXPERIMENT_PROMPTS),
                        help="Slakh-FT prompts of E2 to show (none: no experiment section)")
    parser.add_argument("--out", type=Path, default=PAGE_PATH)
    args = parser.parse_args(argv)

    pools, audio = collect_pools(load_selection(args.selection), args.bank_dir)
    examples, experiment_audio = collect_experiment(args.experiment_prompts, args.audio_dir)
    audio.update(experiment_audio)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build_page(pools, examples, audio), encoding="utf-8")
    sizes = ", ".join(f"{len(clips)} {label}" for label, clips in pools.items())
    print(f"Pools: {sizes}; experiment prompts: {args.experiment_prompts}")
    print(f"Demo page ({args.out.stat().st_size / 1e6:.1f} MB) -> {args.out}")


if __name__ == "__main__":
    sys.exit(main())
